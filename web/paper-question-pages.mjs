export function taskQuestionPages(lesson) {
  if (lesson?.paper?.part !== 'A') return [];
  const numbers = lesson.questions.map((q) => q.number);
  return (rangesBySource[lesson.paper.questionSourceId] || []).filter(([, first, last]) =>
    numbers.some((number) => number >= first && number <= last),
  );
}
